import type { Pickup } from "./types";
type Polygon = number[][];
const tooth = (x: number, y: number, w = 4): Polygon => [
  [x, y],
  [x + w, y],
  [x + w - 1, y + 6],
  [x + 1, y + 6],
];
const diamond = (x: number, y: number, r: number): Polygon => [
  [x, y - r],
  [x + r, y],
  [x, y + r],
  [x - r, y],
];
const ring = (radius: number, count: number, spiked = false): Polygon =>
  Array.from({ length: count }, (_, i) => {
    const a = (i * Math.PI * 2) / count,
      r = spiked && i % 2 ? radius * 0.65 : radius;
    return [12 + Math.sin(a) * r, 12 + Math.cos(a) * r];
  });
